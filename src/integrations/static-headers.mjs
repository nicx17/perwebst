/**
 * Writes security and cache headers into the build's `_headers` file.
 *
 * Cloudflare serves prerendered pages and public/ files straight from static
 * assets, before the Worker runs, so middleware can't set their headers. This
 * integration hashes every inline script in the built HTML and gives each
 * page an exact-path Content-Security-Policy rule. Astro pages share one
 * policy (the union of their hashes) because the ClientRouter runs the next
 * page's inline scripts under the current page's policy. Standalone pages in
 * public/projects get a policy with only their own hashes.
 *
 * The build fails if a page has inline code the policy would block, if the
 * file breaks Cloudflare's `_headers` limits, or if a background in the
 * rotation is missing one of its image variants.
 */
import { existsSync } from 'node:fs';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  CACHE_RULES,
  REPORT_PATH,
  buildContentSecurityPolicy,
  buildSecurityHeaders,
  extractInlineScripts,
  findBlockedInlineCode,
  hashInlineScript,
  htmlFileToUrlPath,
  renderHeaderRules,
  validateHeadersFile,
} from '../utils/security-headers.ts';

const BEGIN_MARKER = '# BEGIN generated by src/integrations/static-headers.mjs';
const END_MARKER = '# END generated by src/integrations/static-headers.mjs';
const BACKGROUND_VARIANTS = ['.jpg', '.avif', '.webp', '.tiny.webp'];

const listFiles = async (directory) => {
  const entries = await readdir(directory, {
    recursive: true,
    withFileTypes: true,
  });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name));
};

/** Every background in the rotation must have all of its variants on disk. */
const checkBackgrounds = async (rootDir, publicDir) => {
  const colors = JSON.parse(
    await readFile(join(rootDir, 'src/data/background-colors.json'), 'utf8')
  );
  const lightDir = join(publicDir, 'backgrounds/light');
  const missing = Object.keys(colors).flatMap((name) =>
    BACKGROUND_VARIANTS.map((ext) => `${name}${ext}`).filter(
      (file) => !existsSync(join(lightDir, file))
    )
  );
  if (missing.length > 0) {
    throw new Error(
      `Backgrounds in src/data/background-colors.json are missing files in public/backgrounds/light: ${missing.join(', ')}. Run \`npm run optimize:backgrounds\`.`
    );
  }
};

const stripGeneratedBlock = (content) => {
  const start = content.indexOf(BEGIN_MARKER);
  const end = content.indexOf(END_MARKER);
  if (start === -1 || end === -1) {
    return content;
  }
  return content.slice(0, start) + content.slice(end + END_MARKER.length);
};

/** @returns {import('astro').AstroIntegration} */
export default function staticHeaders() {
  let config;

  return {
    name: 'static-headers',
    hooks: {
      'astro:config:done': ({ config: resolved }) => {
        config = resolved;
      },
      'astro:build:start': async () => {
        await checkBackgrounds(
          fileURLToPath(config.root),
          fileURLToPath(config.publicDir)
        );
      },
      'astro:build:done': async ({ logger }) => {
        if (!config.site) {
          throw new Error('static-headers needs `site` in astro.config.mjs.');
        }
        const clientDir = fileURLToPath(config.build.client);
        const publicDir = fileURLToPath(config.publicDir);
        const reportEndpoint = new URL(REPORT_PATH, config.site).toString();

        const htmlFiles = (await listFiles(clientDir)).filter((file) =>
          file.endsWith('.html')
        );
        if (htmlFiles.length === 0) {
          throw new Error(`No HTML found in ${clientDir}; nothing to secure.`);
        }

        const pages = [];
        const blocked = [];
        for (const file of htmlFiles) {
          const relativePath = relative(clientDir, file);
          const html = await readFile(file, 'utf8');
          const hashes = await Promise.all(
            extractInlineScripts(html).map(hashInlineScript)
          );
          for (const snippet of findBlockedInlineCode(html)) {
            blocked.push(`${relativePath}: ${snippet}`);
          }
          pages.push({
            path: htmlFileToUrlPath(relativePath),
            standalone: existsSync(join(publicDir, relativePath)),
            hashes,
          });
        }
        if (blocked.length > 0) {
          throw new Error(
            `Inline event handlers or javascript: URLs would be blocked by the CSP. Move them into scripts:\n${blocked.join('\n')}`
          );
        }

        const sitePolicy = buildContentSecurityPolicy({
          reportEndpoint,
          scriptHashes: [
            ...new Set(
              pages.filter((p) => !p.standalone).flatMap((p) => p.hashes)
            ),
          ].sort(),
        });

        const rules = [
          { pattern: '/*', headers: buildSecurityHeaders(reportEndpoint) },
          ...CACHE_RULES.map(([pattern, value]) => ({
            pattern,
            headers: { 'Cache-Control': value },
          })),
          ...pages
            .sort((a, b) => a.path.localeCompare(b.path))
            .map((page) => ({
              pattern: page.path,
              headers: {
                'Content-Security-Policy': page.standalone
                  ? buildContentSecurityPolicy({
                      reportEndpoint,
                      scriptHashes: [...new Set(page.hashes)].sort(),
                      allowGoogleFonts: true,
                    })
                  : sitePolicy,
              },
            })),
        ];

        const headersPath = join(clientDir, '_headers');
        const existing = await readFile(headersPath, 'utf8').then(
          (text) => stripGeneratedBlock(text).trim(),
          (error) => {
            if (error.code === 'ENOENT') return '';
            throw error;
          }
        );
        const generated = `${BEGIN_MARKER}\n${renderHeaderRules(rules)}${END_MARKER}\n`;
        const content = existing ? `${existing}\n\n${generated}` : generated;

        const problems = validateHeadersFile(content);
        if (problems.length > 0) {
          throw new Error(`_headers is invalid:\n${problems.join('\n')}`);
        }
        await writeFile(headersPath, content);

        const standaloneCount = pages.filter((p) => p.standalone).length;
        logger.info(
          `Wrote CSP for ${pages.length} pages (${standaloneCount} standalone) and ${CACHE_RULES.length} cache rules to _headers.`
        );
      },
    },
  };
}
